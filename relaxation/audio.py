"""Mix rain ambience + YuE2 ambient music bed into a single WAV for the final video.

Rain source: relaxation/assets/rain.mp3 (expected CC0 file placed by the owner).
Fallback: pink noise generated by ffmpeg when the file is absent.

Music: an ambient-sleep YuE2 track made via story3/music.py from the session's own caption (relaxation/variety.py).
The YuE2 track is looped with cross-fades and mixed under the rain.

Final: stereo 48kHz WAV normalised to FINAL_LUFS (-14), ready to embed in the MP4."""
import asyncio
import random
import re
import shutil
import subprocess
from pathlib import Path

import config
from story3 import store as media, music as music_mod
from story3.voice import MediaError

from . import models as M, store

ASSETS_DIR = Path(__file__).with_name("assets")
RAIN_FILE = ASSETS_DIR / M.RAIN_ASSET


def _ffmpeg(args: list[str], cwd: Path | None = None) -> None:
    r = subprocess.run(
        [config.FFMPEG, "-y", "-hide_banner", "-loglevel", "error", *args],
        capture_output=True, text=True, cwd=cwd, encoding="utf-8", errors="replace",
    )
    if r.returncode != 0:
        last = (r.stderr or r.stdout).strip().splitlines()
        raise RuntimeError((last[-1] if last else str(r.returncode))[:240])


def _rain_duration(src: Path) -> float:
    r = subprocess.run([config.FFMPEG, "-hide_banner", "-i", str(src)], capture_output=True, text=True, encoding="utf-8", errors="replace")
    m = re.search(r"Duration:\s*(\d+):(\d+):([\d.]+)", r.stderr or "")
    return int(m.group(1)) * 3600 + int(m.group(2)) * 60 + float(m.group(3)) if m else 0.0


def _loudness(path: Path) -> float | None:
    """Integrated loudness (LUFS) of a file, or None."""
    r = subprocess.run([config.FFMPEG, "-hide_banner", "-nostats", "-i", str(path), "-af", "ebur128", "-f", "null", "-"],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    found = re.findall(r"\bI:\s*(-?[\d.]+)\s*LUFS", r.stderr or "")
    return float(found[-1]) if found else None


XFADE_S = 4.0


def _rain_unit(work: Path) -> Path | None:
    """One seamless loop of the steady middle of the rain recording.

    The recording starts in silence and takes about 35 s to swell and fades out at the end, so looping the
    whole file made the rain nearly silent at the start and dipped it at every restart. Here only the steady
    part is used, and its tail is cross-faded into its head, so the unit repeats with no gap and no change
    of level. None when the file is too short to cut."""
    dur = _rain_duration(RAIN_FILE)
    start = 40.0 if dur >= 95 else min(6.0, max(0.0, dur * 0.1))
    length = min(47.0, dur - start - 4.0)
    if length < 14:
        return None
    x = XFADE_S
    unit = work / "rain_unit.wav"
    graph = (
        f"[0:a]atrim=0:{x},asetpts=PTS-STARTPTS[head];"
        f"[0:a]atrim={x}:{length - x},asetpts=PTS-STARTPTS[body];"
        f"[0:a]atrim={length - x}:{length},asetpts=PTS-STARTPTS[tail];"
        f"[tail][head]acrossfade=d={x}:c1=tri:c2=tri[seam];"
        "[seam][body]concat=n=2:v=0:a=1,highpass=f=100,aresample=48000,aformat=channel_layouts=stereo[o]"
    )
    try:
        _ffmpeg(["-ss", f"{start:.2f}", "-t", f"{length:.2f}", "-i", str(RAIN_FILE), "-filter_complex", graph, "-map", "[o]", "-c:a", "pcm_s16le", str(unit)])
    except RuntimeError:
        return None
    return unit


def _rain_loop(total_s: float, out: Path, level: float = M.RAIN_LUFS) -> None:
    """Rain bed of `total_s` seconds at `level` LUFS (the rain is the background): the steady part of rain.mp3
    looped seamlessly with one fixed gain (no adaptive levelling, which made the level swell and sag), or pink noise."""
    fade_out = min(5.0, total_s / 10)
    fades = f"afade=t=in:d=3,afade=t=out:st={max(0.0, total_s - fade_out):.2f}:d={fade_out:.2f}"
    unit = _rain_unit(out.parent) if RAIN_FILE.is_file() else None
    if unit is not None:
        lufs = _loudness(unit)
        gain = (level - lufs) if lufs is not None else 0.0
        _ffmpeg(["-stream_loop", "-1", "-i", str(unit), "-af", f"volume={gain:.2f}dB,{fades}",
                 "-t", f"{total_s:.2f}", "-c:a", "pcm_s16le", str(out)])
    elif RAIN_FILE.is_file():
        # too short to cut: the whole file looped (old behaviour)
        graph = (
            f"aloop=loop=-1:size=2e9,atrim=0:{total_s:.2f},asetpts=PTS-STARTPTS,highpass=f=100,"
            f"loudnorm=I={level}:TP=-1.5:LRA=9,{fades},aresample=48000,aformat=channel_layouts=stereo[o]"
        )
        _ffmpeg(["-stream_loop", "-1", "-i", str(RAIN_FILE), "-filter_complex", graph, "-map", "[o]",
                 "-t", f"{total_s:.2f}", "-c:a", "pcm_s16le", str(out)])
    else:
        # pink noise fallback (owner should replace with a real rain file)
        graph = (
            f"anoisesrc=colour=pink:r=48000:d={total_s:.2f}:a=0.25,highpass=f=200,lowpass=f=8000,"
            f"loudnorm=I={level}:TP=-1.5:LRA=9,{fades},aformat=channel_layouts=stereo[o]"
        )
        _ffmpeg(["-filter_complex", graph, "-map", "[o]", "-t", f"{total_s:.2f}", "-c:a", "pcm_s16le", str(out)])


def _mix(rain: Path, music: Path | None, total_s: float, out: Path) -> None:
    """Combine rain (foreground) + optional music bed into the final WAV at FINAL_LUFS."""
    if music is None:
        # just normalise the rain alone
        _ffmpeg(["-i", str(rain),
                 "-af", f"loudnorm=I={M.FINAL_LUFS}:TP=-1.5:LRA=11,aresample=48000",
                 "-t", f"{total_s:.2f}", "-c:a", "pcm_s16le", str(out)])
        return

    # both are already at their own levels (music in front, rain behind, set in make()): add them,
    # normalise the sum and hold the peak. The old code ducked the music a second time here (-16 dB
    # on top of its own -34 LUFS), which made it inaudible.
    graph = (
        "[0:a][1:a]amix=inputs=2:normalize=0,"
        f"loudnorm=I={M.FINAL_LUFS}:TP=-2:LRA=11,"
        "alimiter=limit=0.84:level=disabled,"
        "aresample=48000[o]"
    )
    _ffmpeg(["-i", str(rain), "-i", str(music),
             "-filter_complex", graph, "-map", "[o]",
             "-t", f"{total_s:.2f}", "-c:a", "pcm_s16le", str(out)])


async def make(session_id: str, s: dict | None = None, key: str = "",
               progress=None, force: bool = False) -> dict:
    """Make the final mixed audio for a session. Returns a media row (rl_audio)."""
    from story import settings as settings_mod
    s = s or settings_mod.get()
    api_key = key or settings_mod.api_key()

    if not force:
        existing = store.chosen(session_id, M.KIND_AUDIO)
        if existing:
            return existing

    session = store.get(session_id)
    settings = session.get("settings") or {}
    total_s = M.total_s(settings)

    # ── YuE2 ambient music (optional) ─────────────────────────────────────────
    music_item = None
    music_error = ""
    if settings.get("music_enabled", True):
        scene = settings.get("scene") or M.DEFAULT_SCENE
        music_cfg = music_mod.norm({
            "enabled": True,
            "level": float(settings.get("music_level") or M.MUSIC_LUFS),
            "plan": M.music_recipe(scene, settings.get("music_plan")),
            "seed": int(settings.get("music_seed") or settings.get("seed") or 7),      # its own seed: a new take does not touch the picture
        })
        if progress:
            progress(0, 3, "generating ambient music loop")
        try:
            music_item = await music_mod.make(
                session_id, music_cfg, total_s, s, api_key, progress=None, force=False,
            )
        except MediaError as e:
            music_item = None   # fallback: rain only, but say so (the card shows it)
            music_error = str(e)[:300]

    it = media.add(session_id, M.KIND_AUDIO, "audio", 0, "running",
                   {"total_s": total_s, "music": bool(music_item)})
    work = media.media_dir(session_id, f"work/{it['id']}")

    try:
        if progress:
            progress(1, 3, "mixing rain + music")

        rain_wav = work / "rain.wav"
        await asyncio.to_thread(_rain_loop, total_s, rain_wav, float(settings.get("rain_level") or M.RAIN_LUFS))

        music_bed: Path | None = None
        if music_item:
            music_bed = await asyncio.to_thread(
                music_mod.bed_from_track, config.FFMPEG, music_item, total_s, work,
                float(settings.get("music_level") or M.MUSIC_LUFS), True,
            )

        out = work / "audio_mix.wav"
        await asyncio.to_thread(_mix, rain_wav, music_bed, total_s, out)

        # copy final mix to permanent location
        perm_dir = media.media_dir(session_id, "audio")
        name = f"audio-a{it['attempt']}.wav"
        perm = perm_dir / name
        await asyncio.to_thread(shutil.copy2, str(out), str(perm))

        if progress:
            progress(3, 3, "audio done")

        done = media.update(it["id"], status="done", file=f"audio/{name}",
                            meta={"total_s": total_s, "music": bool(music_item), "music_id": (music_item or {}).get("id", ""),
                                  "music_error": music_error, "rain_fallback": not RAIN_FILE.is_file()})
        shutil.rmtree(work, ignore_errors=True)      # the intermediate rain / music / mix files are about 2 GB each for 3 hours
        return done
    except (RuntimeError, OSError) as e:
        media.update(it["id"], status="failed", meta={"error": str(e)[:300]})
        raise MediaError(f"audio mix failed: {e}") from e


async def regenerate_music(session_id: str, s: dict | None = None, key: str = "", instrument: str = "", progress=None) -> dict:
    """Make the music again (a new seed, so a new take) and put it into the finished video.

    `instrument`: "" keeps the instrument, "other" picks another of the theme's instruments, or a name to use.
    The audio is mixed again; when the video exists its picture is copied (no re-encode) and only the sound is replaced,
    so this takes minutes, not the encode of the whole video. Returns {audio, video}."""
    from story import settings as settings_mod
    from . import publish, variety, video
    s = s or settings_mod.get()
    key = key or settings_mod.api_key()
    session = store.get(session_id)
    st = session.setdefault("settings", {})
    scene = st.get("scene") or M.DEFAULT_SCENE
    plan = dict(st.get("music_plan") or {})
    old_instrument = plan.get("instrument", "")
    rng = random.Random()
    if instrument:
        if instrument == "other":
            hist = [{"scene": scene, "instrument": old_instrument, "mood": plan.get("mood", "")}] + variety.history()
            plan = variety.pick_music(scene, hist, rng)
        else:
            plan = {**plan, "instrument": instrument}
            plan["caption"] = M.music_caption(instrument, plan.get("secondary") or M.MUSIC_SECONDARY[0], plan.get("mood") or M.MUSIC_MOODS[0], int(plan.get("bpm") or 58))
        st["music_plan"] = plan
    st["music_seed"] = rng.randrange(1, 2 ** 31 - 1)
    st["music_enabled"] = True
    store.save(session)

    if progress:
        progress(0, 3, "making new music")
    a = await make(session_id, s, key, progress=progress, force=True)
    if not a["meta"].get("music"):
        raise MediaError("the new music could not be made: " + (a["meta"].get("music_error") or "see the gateway"))
    v = None
    if store.chosen(session_id, M.KIND_FINAL):
        if progress:
            progress(2, 3, "putting the new sound into the video")
        v = await asyncio.to_thread(video.remux, session_id)
    if plan.get("instrument") != old_instrument:
        try:
            await publish.generate(session_id, s, force=True)        # the description names the instrument
        except Exception:  # noqa: BLE001 - not worth failing the new music for
            pass
    if progress:
        progress(3, 3, "done")
    return {"audio": a["id"], "video": (v or {}).get("id", "")}
